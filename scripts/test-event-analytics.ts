import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { mkdir } from "node:fs/promises";
import { pathToFileURL } from "node:url";
import nextEnv from "@next/env";
import { eq, inArray } from "drizzle-orm";
import * as tables from "../db/schema";
import { getDatabase } from "../lib/db/client";
import { hashToken } from "../lib/auth/tokens";
import { loadEventAnalytics, loadEventRevenue } from "../lib/server/event-analytics";

nextEnv.loadEnvConfig(process.cwd());
const origin = process.env.SMOKE_ORIGIN ?? "http://localhost:5180";
assert.ok(["localhost", "127.0.0.1"].includes(new URL(origin).hostname));
const db = getDatabase();
const userId = randomUUID();
const organizerId = randomUUID();
const eventIds = [randomUUID(), randomUUID()];
const token = randomUUID();
const email = `analytics-${userId}@example.invalid`;
const slug = `analytics-${eventIds[0]}`;
const seatSlug = `analytics-${eventIds[1]}`;
let browser: { close(): Promise<void> } | undefined;
type FinanceResponse = { data: { transactions: unknown[]; summary: { grossMinor: number; platformFeesMinor: number; refundedMinor: number }; eventRevenue: unknown[]; payoutBalanceAvailable: boolean } };
async function get(path: string, authenticated = true) {
  return fetch(`${origin}${path}`, { headers: authenticated ? { cookie: `nasa_session=${token}` } : {}, redirect: "manual", signal: AbortSignal.timeout(90_000) });
}

try {
  await db.insert(tables.users).values({ id: userId, email, emailNormalized: email, firstName: "Analytics", lastName: "Test", status: "active" });
  await db.insert(tables.organizers).values({ id: organizerId, slug: `analytics-${organizerId}`, name: "Analytics verification", email, status: "active" });
  await db.insert(tables.organizerMembers).values({ organizerId, userId, userKey: userId, email, role: "owner", status: "active", eventScope: "all" });
  await db.insert(tables.userSessions).values({ userId, tokenHash: hashToken(token), expiresAt: new Date(Date.now() + 3600_000) });
  await db.insert(tables.events).values(eventIds.map((id, index) => ({ id, organizerId, createdByUserId: userId, slug: index ? seatSlug : slug, title: index ? "Seated analytics verification" : "Analytics verification", shortTitle: "Analytics", category: "Community", status: "draft", pricingMode: "paid", admissionMode: index ? "selectable" : "general", startAt: new Date("2027-01-01T12:00:00Z"), venue: "Test venue", address: "Test address", city: "Lagos", capacity: index ? 4 : 120 })));
  const [category] = await db.insert(tables.ticketCategories).values({ eventId: eventIds[0], name: "Standard", priceMinor: 10000, quantityAvailable: 120, quantitySold: 101 }).returning();
  const bookingRows = await db.insert(tables.bookings).values(Array.from({ length: 101 }, (_, index) => ({ eventId: eventIds[0], code: `QA-${userId}-${index}`, qrTokenHash: randomUUID(), idempotencyKey: randomUUID(), status: "confirmed", buyerName: `Buyer ${index}`, buyerEmail: email, currency: "NGN", subtotalMinor: 10000, totalMinor: 10000, platformFeeMinor: 500, paymentStatus: "paid", confirmedAt: new Date() }))).returning();
  const attendees = await db.insert(tables.bookingAttendees).values(bookingRows.map((booking, index) => ({ bookingId: booking.id, ticketCategoryId: category.id, name: `Guest ${index + 1}`, priceMinor: 10000, priceBandName: "Standard" }))).returning();
  const payments = await db.insert(tables.paymentTransactions).values(bookingRows.map((booking) => ({ bookingId: booking.id, provider: "test", providerReference: randomUUID(), amountMinor: 10000, currency: "NGN", platformFeeMinor: 500, providerFeeMinor: 100, organizerNetMinor: 9400, status: "paid" }))).returning();
  await db.insert(tables.checkIns).values({ bookingAttendeeId: attendees[0].id, entrance: "Test", operationId: randomUUID() });
  await db.insert(tables.checkIns).values({ bookingAttendeeId: attendees[1].id, entrance: "Test", operationId: randomUUID(), reversedAt: new Date() });
  const [refundRequest] = await db.insert(tables.refundRequests).values({ organizerId, bookingId: bookingRows[0].id, requestedBy: userId, amountMinor: 1000, reason: "Analytics fixture", status: "completed" }).returning();
  await db.insert(tables.refunds).values({ refundRequestId: refundRequest.id, paymentTransactionId: payments[0].id, amountMinor: 1000, status: "processed" });
  const [band] = await db.insert(tables.priceBands).values({ eventId: eventIds[1], name: "Premium", priceMinor: 20000, color: "#008877" }).returning();
  const [table] = await db.insert(tables.layoutObjects).values({ eventId: eventIds[1], type: "round-table", label: "Table 1", presentation: {} }).returning();
  const seatRows = await db.insert(tables.seats).values(["booked", "booked", "available", "blocked"].map((status, i) => ({ eventId: eventIds[1], layoutObjectId: table.id, stableKey: `s${i}`, label: `Seat ${i + 1}`, shortLabel: String(i + 1), priceBandId: band.id, priceOverrideMinor: i === 1 ? 0 : null, status }))).returning();
  const [group] = await db.insert(tables.bookings).values({ eventId: eventIds[1], code: `QA-GROUP-${userId}`, qrTokenHash: randomUUID(), idempotencyKey: randomUUID(), status: "confirmed", buyerName: "Group buyer", buyerEmail: email, currency: "NGN", subtotalMinor: 20000, totalMinor: 20000, paymentStatus: "paid", confirmedAt: new Date() }).returning();
  const groupAttendees = await db.insert(tables.bookingAttendees).values([{ bookingId: group.id, seatId: seatRows[0].id, name: "Ada Confirmed", priceMinor: 20000, priceBandName: "Premium" }, { bookingId: group.id, seatId: seatRows[1].id, name: "Ben Expected", priceMinor: 0, priceBandName: "Complimentary" }]).returning();
  await db.insert(tables.checkIns).values({ bookingAttendeeId: groupAttendees[0].id, entrance: "Test", operationId: randomUUID() });

  const data = await loadEventAnalytics({ id: eventIds[0], admissionMode: "general", timezone: "Africa/Lagos" });
  assert.equal(data.summary.checkedIn, 1, "Reversed admission must not be counted");
  assert.equal(data.summary.confirmed, 101);
  assert.equal(data.summary.available, 19);
  const revenue = await loadEventRevenue(eventIds);
  assert.equal(revenue.reduce((sum, row) => sum + row.collectedMinor, 0), 1030000);
  assert.equal(revenue.reduce((sum, row) => sum + row.refundedMinor, 0), 1000);
  const response = await get("/api/v1/workspaces/current/finance");
  assert.equal(response.status, 200);
  const finance = (await response.json() as FinanceResponse).data;
  assert.equal(finance.transactions.length, 100);
  assert.equal(finance.summary.grossMinor, 1010000, "Totals must include transactions beyond the latest 100");
  assert.equal(finance.summary.platformFeesMinor, 50500);
  assert.equal(finance.summary.refundedMinor, 1000);
  assert.equal(finance.eventRevenue.length, 2);
  assert.equal((await get("/api/v1/workspaces/current/finance", false)).status, 403);
  for (const path of [`/organizer/events/${slug}/analytics`, `/organizer/events/${seatSlug}/analytics`, "/organizer/events", "/organizer/finance"]) assert.equal((await get(path)).status, 200, path);
  console.log("Database and HTTP checks passed: totals beyond 100 transactions, refunds, group admissions, reversed check-in, event revenue, access guards.");

  if (process.env.ANALYTICS_PLAYWRIGHT_PATH) {
    const { chromium } = await import(pathToFileURL(process.env.ANALYTICS_PLAYWRIGHT_PATH).href);
    const launched = await chromium.launch({ headless: true, channel: process.env.ANALYTICS_BROWSER_CHANNEL });
    browser = launched;
    const context = await launched.newContext({ viewport: { width: 1440, height: 1000 } });
    await context.addCookies([{ name: "nasa_session", value: token, url: origin }]);
    const page = await context.newPage();
    const errors: string[] = [];
    page.on("pageerror", (error: Error) => errors.push(error.message));
    await page.goto(`${origin}/organizer/events/${seatSlug}/analytics`, { waitUntil: "networkidle" });
    await page.waitForFunction(() => {
      const metrics = document.querySelector(".ea-metrics");
      return metrics && getComputedStyle(metrics).display === "grid";
    });
    const details = page.locator("#analytics-details");
    assert.equal(await details.count(), 0, "Dense records are hidden on first load");
    await page.locator("#analytics-summary").getByRole("img", { name: "50% of capacity confirmed" }).waitFor();
    await mkdir("outputs/analytics", { recursive: true });
    await page.screenshot({ path: "outputs/analytics/summary-desktop.png", fullPage: true });
    await page.locator("#analytics-summary").getByRole("button", { name: /^Set aside/ }).click();
    assert.equal(await details.locator("tbody tr").count(), 1, "Set aside opens only unavailable inventory");
    await page.getByRole("button", { name: /^Capacity 4/ }).click();
    assert.equal(await details.locator("tbody tr").count(), 4);
    await page.getByRole("button", { name: /^Confirmed 2/ }).click();
    assert.equal(await details.locator("tbody tr").count(), 2);
    assert.ok((await details.innerText()).includes("Ben Expected"));
    await page.getByRole("button", { name: "Filters", exact: true }).click();
    await page.locator(".ea-filters select").last().selectOption("expected");
    assert.equal(await details.locator("tbody tr").count(), 1);
    assert.ok((await details.innerText()).includes("Ben Expected"));
    await page.getByRole("button", { name: /^Available 1/ }).click();
    assert.equal(await details.locator("tbody tr").count(), 1);
    assert.ok((await details.innerText()).includes("Seat 3"));
    await page.getByRole("button", { name: /^Checked in 1/ }).click();
    assert.ok((await details.innerText()).includes("Ada Confirmed"));
    await page.getByRole("button", { name: /^Capacity 4/ }).click();
    await page.getByLabel("Search analytics").fill("Seat 4");
    assert.equal(await details.locator("tbody tr").count(), 1);
    await page.getByLabel("Search analytics").fill("");
    await mkdir("outputs/analytics", { recursive: true });
    await page.evaluate(() => window.scrollTo({ top: 0, behavior: "instant" }));
    await page.screenshot({ path: "outputs/analytics/desktop-viewport.png" });
    await page.screenshot({ path: "outputs/analytics/desktop.png", fullPage: true });
    await page.locator(".ea-report-nav").getByRole("button", { name: "Revenue", exact: true }).click();
    assert.equal(await details.count(), 0, "Guest table is absent in Revenue view");
    assert.equal(await page.locator(".ea-finance").count(), 1);
    await page.screenshot({ path: "outputs/analytics/revenue-desktop.png", fullPage: true });
    await page.getByRole("button", { name: "Revenue trend", exact: true }).click();
    assert.equal(await page.locator(".ea-finance").count(), 0);
    assert.equal(await page.locator(".ea-chart").count(), 1, "Only one chart renders at a time");
    assert.equal(await page.locator(".ea-segments").getByRole("button", { name: "Revenue", exact: true }).getAttribute("aria-pressed"), "true");
    await page.screenshot({ path: "outputs/analytics/trends-desktop.png", fullPage: true });
    await page.getByLabel("Trend report").selectOption("arrivals");
    await page.getByRole("button", { name: "View guests still expected" }).click();
    assert.equal(await details.locator("tbody tr").count(), 1);
    assert.ok((await details.innerText()).includes("Ben Expected"));
    await page.locator(".ea-report-nav").getByRole("button", { name: "Trends" }).click();
    await page.getByLabel("Trend report").selectOption("bands");
    await page.locator(".ea-band-list").getByRole("button", { name: "Premium" }).click();
    assert.equal(await details.locator("tbody tr").count(), 1);
    assert.ok((await details.innerText()).includes("Ada Confirmed"));
    await page.getByRole("button", { name: /^Capacity 4/ }).click();
    await page.getByLabel("Search analytics").fill("Seat 3");
    await page.locator(".ea-report-nav").getByRole("button", { name: "Revenue", exact: true }).click();
    await page.locator(".ea-report-nav").getByRole("button", { name: /^Guests/ }).click();
    assert.equal(await page.getByLabel("Search analytics").inputValue(), "Seat 3", "Search persists between report views");
    await page.getByRole("button", { name: "Clear", exact: true }).click();
    for (const width of [768, 390]) {
      await page.setViewportSize({ width, height: 900 });
      await page.getByRole("button", { name: "Summary", exact: true }).click();
      await page.screenshot({ path: `outputs/analytics/summary-${width}.png`, fullPage: true });
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), `Summary fits at ${width}px`);
      await page.getByRole("button", { name: /^Available 1/ }).click();
      await page.locator(".ea-availability-bands").getByRole("button", { name: /Premium/ }).click();
      assert.equal(await details.locator("tbody tr").count(), 1);
      await page.getByRole("button", { name: /^Capacity 4/ }).click();
      await page.evaluate(() => window.scrollTo({ top: 0, behavior: "instant" }));
      await page.screenshot({ path: `outputs/analytics/${width}-viewport.png` });
      await page.screenshot({ path: `outputs/analytics/${width}.png`, fullPage: true });
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), `No page overflow at ${width}px`);
      for (const report of ["Revenue", "Trends"]) {
        await page.locator(".ea-report-nav").getByRole("button", { name: report, exact: true }).click();
        await page.evaluate(() => window.scrollTo({ top: 0, behavior: "instant" }));
        await page.screenshot({ path: `outputs/analytics/${report.toLowerCase()}-${width}.png`, fullPage: true });
        assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), `${report} fits at ${width}px`);
      }
      await page.locator(".ea-report-nav").getByRole("button", { name: /^Guests/ }).click();
    }
    await page.goto(`${origin}/organizer/events/${slug}/analytics`, { waitUntil: "networkidle" });
    await page.getByRole("button", { name: "Details", exact: true }).click();
    assert.ok((await page.locator(".ea-table thead").innerText()).includes("Ticket category"));
    await page.getByRole("button", { name: /^Confirmed 101/ }).click();
    assert.equal(await page.locator(".ea-table tbody tr").count(), 25);
    await page.getByRole("button", { name: "Next page", exact: true }).click();
    assert.ok((await page.locator(".ea-pagination").innerText()).includes("26-50"));
    await page.goto(`${origin}/organizer/events`, { waitUntil: "networkidle" });
    assert.equal(await page.locator(".ea-event-revenue").count(), 2);
    assert.ok((await page.locator(".ea-portfolio-total").innerText()).includes("10,300"));
    await page.goto(`${origin}/organizer/finance`, { waitUntil: "networkidle" });
    await page.getByRole("heading", { name: "Revenue by event" }).waitFor();
    assert.ok((await page.locator(".ea-portfolio-total").innerText()).includes("10,300"));
    assert.deepEqual(errors, []);
    console.log("Browser checks passed: all filters, confirmation vs check-in, search, category inventory, pagination, revenue graph, desktop/tablet/mobile layout.");
  }
  await db.update(tables.organizerMembers).set({ eventScope: slug }).where(eq(tables.organizerMembers.userId, userId));
  const scoped = (await (await get("/api/v1/workspaces/current/finance")).json() as FinanceResponse).data;
  assert.equal(scoped.eventRevenue.length, 1);
  assert.equal(scoped.payoutBalanceAvailable, false);
  const restricted = await get(`/organizer/events/${seatSlug}/analytics`);
  const restrictedHtml = await restricted.text();
  assert.ok(restricted.status === 404 || restrictedHtml.includes("NEXT_HTTP_ERROR_FALLBACK;404"));
  assert.ok(!restrictedHtml.includes("Ada Confirmed"));
  console.log("Assigned-event scoping passed.");
} finally {
  await browser?.close();
  const fixtureBookings = await db.select({ id: tables.bookings.id }).from(tables.bookings).where(inArray(tables.bookings.eventId, eventIds));
  const fixtureRequests = await db.select({ id: tables.refundRequests.id }).from(tables.refundRequests).where(eq(tables.refundRequests.organizerId, organizerId));
  if (fixtureRequests.length) await db.delete(tables.refunds).where(inArray(tables.refunds.refundRequestId, fixtureRequests.map((row) => row.id)));
  await db.delete(tables.refundRequests).where(eq(tables.refundRequests.organizerId, organizerId));
  if (fixtureBookings.length) await db.delete(tables.paymentTransactions).where(inArray(tables.paymentTransactions.bookingId, fixtureBookings.map((row) => row.id)));
  await db.delete(tables.bookings).where(inArray(tables.bookings.eventId, eventIds));
  await db.delete(tables.events).where(inArray(tables.events.id, eventIds));
  await db.delete(tables.organizers).where(eq(tables.organizers.id, organizerId));
  await db.delete(tables.users).where(eq(tables.users.id, userId));
  console.log("Temporary analytics fixtures removed.");
}
